import { describe, expect, it } from 'vitest'
import {
  isPlausibleYouTubeSource,
  selectMatchingYouTubeSource,
} from '../../src/adapters/shared/youtube-source-match'
import type { BridgePayload } from '../../src/adapters/shared/page-bridge'

function payload(title: string, durationMs: number, videoId = 'aaaaaaaaaaa'): BridgePayload {
  return {
    videoId,
    metadata: { title, durationMs },
    tracks: [{
      baseUrl: 'https://www.youtube.com/api/timedtext?v=aaaaaaaaaaa&lang=en',
      languageCode: 'en',
      label: 'English',
      vssId: '.en',
      isAutoGenerated: false,
    }],
  }
}

describe('YouTube source matching', () => {
  it('rejects a much shorter unrelated YouTube video', () => {
    expect(isPlausibleYouTubeSource(
      '《经济学人》杂志主编对埃隆·马斯克的访谈',
      3_600_000,
      payload('厦门姜母鸭探店', 600_000, 'bbbbbbbbbbb'),
    )).toBe(false)
  })

  it('selects the YouTube video whose duration and title match the Bilibili upload', () => {
    const food = {
      videoId: 'bbbbbbbbbbb',
      payload: payload('厦门姜母鸭探店', 600_000, 'bbbbbbbbbbb'),
    }
    const interview = {
      videoId: 'ccccccccccc',
      payload: payload('The Economist interviews Elon Musk', 3_500_000, 'ccccccccccc'),
    }
    const selected = selectMatchingYouTubeSource(
      'Elon Musk 经济学人访谈',
      3_600_000,
      [food, interview],
    )
    expect(selected?.videoId).toBe('ccccccccccc')
  })

  it('does not guess from duration alone when the title has no overlap', () => {
    const selected = selectMatchingYouTubeSource(
      '《经济学人》杂志主编对埃隆·马斯克的访谈',
      3_600_000,
      [{
        videoId: 'bbbbbbbbbbb',
        payload: payload('Unrelated conference recording', 3_590_000, 'bbbbbbbbbbb'),
      }],
    )
    expect(selected).toBeNull()
  })

  it('rejects ambiguous candidates instead of silently choosing the first one', () => {
    const selected = selectMatchingYouTubeSource(
      'Elon Musk interview',
      3_600_000,
      [
        {
          videoId: 'bbbbbbbbbbb',
          payload: payload('Elon Musk interview part one', 3_590_000, 'bbbbbbbbbbb'),
        },
        {
          videoId: 'ccccccccccc',
          payload: payload('Elon Musk interview full', 3_580_000, 'ccccccccccc'),
        },
      ],
    )
    expect(selected).toBeNull()
  })

  it('prefers a source-marked YouTube id when several durations match', () => {
    const first = {
      videoId: 'bbbbbbbbbbb',
      payload: payload('Channel vlog', 3_500_000, 'bbbbbbbbbbb'),
    }
    const original = {
      videoId: 'ccccccccccc',
      payload: payload('The Economist interviews Elon Musk', 3_550_000, 'ccccccccccc'),
    }
    const selected = selectMatchingYouTubeSource(
      '《经济学人》杂志主编对埃隆·马斯克的访谈',
      3_600_000,
      [first, original],
      new Set(['ccccccccccc']),
    )
    expect(selected?.videoId).toBe('ccccccccccc')
  })
})
