import { describe, expect, it, vi } from 'vitest'
import { BilibiliAdapter } from '../../src/adapters/bilibili/adapter'
import type { BilibiliContextPayload } from '../../src/adapters/bilibili/schemas'
import contextFixture from '../fixtures/bilibili/player-context.json'
import subtitlesFixture from '../fixtures/bilibili/player-subtitles.json'
import bodyFixture from '../fixtures/bilibili/subtitle-body.json'
import youtubePlayerResponse from '../fixtures/youtube/player-response.json'

const bridgePayload = contextFixture as BilibiliContextPayload

function createFetch() {
  return vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
    const url = typeof input === 'string' ? input : input.toString()
    // Route: subtitle list API
    if (url.includes('/x/player/v2')) {
      return new Response(JSON.stringify(subtitlesFixture), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      })
    }
    // Route: subtitle body download
    if (url.includes('hdslb.com')) {
      return new Response(JSON.stringify(bodyFixture), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      })
    }
    return new Response('{}', { status: 404 })
  })
}

describe('BilibiliAdapter', () => {
  it('rejects subtitle lists returned for a different video identity', async () => {
    const fetchImpl = vi.fn(async (input: RequestInfo | URL) => {
      if (String(input).includes('/x/player/v2')) return new Response(JSON.stringify({
        ...subtitlesFixture, data: { ...subtitlesFixture.data, bvid: 'BV-other', cid: 999 },
      }))
      return new Response('{}', { status: 404 })
    })
    await expect(new BilibiliAdapter(bridgePayload, fetchImpl).getSubtitleTracks())
      .rejects.toMatchObject({ code: 'SUBTITLE_UNRELIABLE' })
  })
  function publisherOpusHtml(paragraphs: string[], authorMid = 1104053532) {
    return `<script>window.__INITIAL_STATE__=${JSON.stringify({
      detail: {
        modules: [
          { module_type: 'MODULE_TYPE_TITLE', module_title: { text: '当前视频完整文稿' } },
          { module_type: 'MODULE_TYPE_AUTHOR', module_author: { mid: authorMid, name: '科技频道' } },
          {
            module_type: 'MODULE_TYPE_CONTENT',
            module_content: {
              paragraphs: paragraphs.map((value) => ({
                text: { nodes: [{ word: { words: value } }] },
              })),
            },
          },
        ],
      },
    })};(function(){})();</script>`
  }

  it('supports bilibili.com URLs', () => {
    const adapter = new BilibiliAdapter(bridgePayload, createFetch())
    expect(adapter.supports(new URL('https://www.bilibili.com/video/BV1xx411c7mD'))).toBe(true)
    expect(adapter.supports(new URL('https://www.youtube.com/watch?v=test123'))).toBe(false)
    expect(adapter.supports(new URL('https://bilibili.com/video/BV123'))).toBe(true)
  })

  it('returns video metadata', async () => {
    const adapter = new BilibiliAdapter(bridgePayload, createFetch())
    const metadata = await adapter.getVideoMetadata()

    expect(metadata).toMatchObject({
      platform: 'bilibili',
      videoId: 'BV1xx411c7mD',
      title: '人工智能入门教程',
      author: '科技频道',
      canonicalUrl: 'https://www.bilibili.com/video/BV1xx411c7mD',
      durationMs: 900000,
    })
  })

  it('keeps the current Bilibili part in the canonical URL', async () => {
    const adapter = new BilibiliAdapter({ ...bridgePayload, page: 2 }, createFetch())
    await expect(adapter.getVideoMetadata()).resolves.toMatchObject({
      canonicalUrl: 'https://www.bilibili.com/video/BV1xx411c7mD?p=2',
    })
  })

  it('does not merge unscoped view subtitles into the current cid', async () => {
    const viewOnlyTrack = subtitlesFixture.data.subtitle!.subtitles[0]!
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('/x/player/v2')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({
          code: 0,
          data: { desc: '', subtitle: { list: [viewOnlyTrack] } },
        }), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)

    await expect(adapter.getSubtitleTracks()).rejects.toMatchObject({ code: 'NO_SUBTITLE' })
  })

  it('maps Bilibili subtitle tracks to domain objects', async () => {
    const adapter = new BilibiliAdapter(bridgePayload, createFetch())
    const tracks = await adapter.getSubtitleTracks()

    expect(tracks).toEqual([
      {
        id: '12345',
        language: 'zh-CN',
        label: '中文（简体）',
        isAutoGenerated: false,
        sourceGroup: 'bilibili:BV1xx411c7mD:987654321',
      },
      {
        id: '12346',
        language: 'en',
        label: '英语',
        isAutoGenerated: true,
        sourceGroup: 'bilibili:BV1xx411c7mD:987654321',
      },
    ])
  })

  it('maps Bilibili subtitle seconds to milliseconds', async () => {
    const adapter = new BilibiliAdapter(bridgePayload, createFetch())
    const tracks = await adapter.getSubtitleTracks()

    const cues = await adapter.getCues(tracks[0]!)
    expect(cues).toHaveLength(3)
    expect(cues[0]).toEqual({
      id: 'bili-0',
      startMs: 1500,
      endMs: 3200,
      text: '欢迎来到测试视频。',
    })
    expect(cues[1]).toEqual({
      id: 'bili-1',
      startMs: 3500,
      endMs: 6000,
      text: '今天我们来讨论人工智能。',
    })
    expect(cues[2]).toEqual({
      id: 'bili-2',
      startMs: 6200,
      endMs: 9500,
      text: 'AI正在改变世界。',
    })
  })

  it('rejects a valid subtitle body without any text cues', async () => {
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      return new Response(JSON.stringify(
        url.includes('/x/player/v2') ? subtitlesFixture : { body: [] },
      ), { status: 200 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)
    const tracks = await adapter.getSubtitleTracks()

    await expect(adapter.getCues(tracks[0]!)).rejects.toThrow('没有可提取的文字内容')
  })

  it('throws NO_SUBTITLE when API returns empty list', async () => {
    const emptyFetch = vi.fn().mockResolvedValue(
      new Response(JSON.stringify({ code: 0, data: {} }), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      }),
    )
    const adapter = new BilibiliAdapter(bridgePayload, emptyFetch)

    await expect(adapter.getSubtitleTracks()).rejects.toMatchObject({
      code: 'NO_SUBTITLE',
    })
  })

  it('registers current-page audio transcription as a timestamped track', async () => {
    const adapter = new BilibiliAdapter(bridgePayload, createFetch())
    const cues = [{ id: 'asr-1', startMs: 0, endMs: 2_000, text: 'Hello world' }]
    const track = adapter.registerTranscription('task-1', cues, 'english', 2_000, true)

    expect(track).toMatchObject({
      id: 'bili-asr:task-1',
      language: 'en',
      sourceKind: 'audio-transcription',
      sourceDurationMs: 2_000,
      hasTimestamps: true,
    })
    await expect(adapter.getCues(track)).resolves.toEqual(cues)
  })

  it('discovers and loads an uploader-owned transcript from the pinned reply', async () => {
    const opusId = '1229349644530614295'
    const paragraphs = Array.from({ length: 12 }, (_, index) => `第 ${index + 1} 段${'完整文稿内容'.repeat(12)}`)
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('/x/player/v2')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({
          code: 0,
          data: { desc: '文稿见置顶评论', owner: { mid: 1104053532, name: '科技频道' } },
        }), { status: 200 })
      }
      if (url.includes('/x/v2/reply')) {
        return new Response(JSON.stringify({
          code: 0,
          data: {
            upper: {
              mid: 1104053532,
              top: {
                mid: 1104053532,
                content: { message: `视频文稿：https://www.bilibili.com/opus/${opusId}` },
              },
            },
          },
        }), { status: 200 })
      }
      if (url === `https://www.bilibili.com/opus/${opusId}`) {
        return new Response(publisherOpusHtml(paragraphs), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter({
      ...bridgePayload,
      aid: 116985916622558,
      durationMs: 10 * 60_000,
    }, fetchImpl)

    await expect(adapter.discoverPublisherTranscript()).resolves.toEqual({ status: 'loaded' })
    const tracks = await adapter.getSubtitleTracks()
    const publisherTrack = tracks.find((track) => track.sourceKind === 'publisher-transcript')
    expect(publisherTrack).toMatchObject({
      hasTimestamps: false,
      language: 'zh',
      label: expect.stringContaining('当前视频完整文稿'),
    })
    await expect(adapter.getCues(publisherTrack!)).resolves.toHaveLength(paragraphs.length)
  })

  it('reports an uploader-owned transcript that is access restricted', async () => {
    const opusId = '1229349644530614295'
    const lockedHtml = `<script>window.__INITIAL_STATE__=${JSON.stringify({
      detail: {
        modules: [
          { module_type: 'MODULE_TYPE_TITLE', module_title: { text: '充电专属完整文稿' } },
          { module_type: 'MODULE_TYPE_AUTHOR', module_author: { mid: 1104053532 } },
          {
            module_type: 'MODULE_TYPE_BLOCKED',
            module_blocked: { hint_message: '加入当前UP主的18元档包月充电即可解锁观看' },
          },
        ],
      },
    })};(function(){})();</script>`
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({
          code: 0,
          data: { desc: '', owner: { mid: 1104053532 } },
        }), { status: 200 })
      }
      if (url.includes('/x/v2/reply')) {
        return new Response(JSON.stringify({
          code: 0,
          data: { upper: { mid: 1104053532, top: {
            mid: 1104053532,
            content: { message: `文稿 https://www.bilibili.com/opus/${opusId}` },
          } } },
        }), { status: 200 })
      }
      if (url.includes(`/opus/${opusId}`)) return new Response(lockedHtml, { status: 200 })
      return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)

    await expect(adapter.discoverPublisherTranscript()).resolves.toEqual({
      status: 'locked',
      url: `https://www.bilibili.com/opus/${opusId}`,
      message: '加入当前UP主的18元档包月充电即可解锁观看',
    })
  })

  it('rejects a transcript link when the opus author is not the current uploader', async () => {
    const opusId = '123456789'
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({
          code: 0,
          data: { desc: `文稿 https://www.bilibili.com/opus/${opusId}`, owner: { mid: 42 } },
        }), { status: 200 })
      }
      if (url.includes(`/opus/${opusId}`)) {
        return new Response(publisherOpusHtml(['正文'.repeat(1_000)], 99), { status: 200 })
      }
      return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)

    await expect(adapter.discoverPublisherTranscript()).resolves.toMatchObject({
      status: 'not-found',
    })
  })

  it('rejects non-HTTPS subtitle URLs', async () => {
    const insecureSubs = {
      ...subtitlesFixture,
      data: {
        subtitle: {
          subtitles: [
            {
              id: 1,
              lan: 'zh-CN',
              lan_doc: '中文',
              subtitle_url: 'http://insecure.server/subtitle.json',
            },
          ],
        },
      },
    }
    const insecureFetch = vi.fn().mockResolvedValue(
      new Response(JSON.stringify(insecureSubs), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      }),
    )
    const adapter = new BilibiliAdapter(bridgePayload, insecureFetch)
    const tracks = await adapter.getSubtitleTracks()

    await expect(adapter.getCues(tracks[0]!)).rejects.toMatchObject({
      code: 'SUBTITLE_EXTRACTION_FAILED',
    })
  })

  it('accepts protocol-relative subtitle URLs from the Bilibili CDN', async () => {
    const relativeSubs = structuredClone(subtitlesFixture)
    relativeSubs.data.subtitle!.subtitles[0]!.subtitle_url =
      '//i0.hdslb.com/bfs/ai_subtitle/12345.json'
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      return new Response(JSON.stringify(
        url.includes('/x/player/v2') ? relativeSubs : bodyFixture,
      ), { status: 200 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)
    const tracks = await adapter.getSubtitleTracks()

    await expect(adapter.getCues(tracks[0]!)).resolves.toHaveLength(3)
    expect(fetchImpl).toHaveBeenLastCalledWith(
      'https://i0.hdslb.com/bfs/ai_subtitle/12345.json',
      expect.objectContaining({ credentials: 'include' }),
    )
  })

  it('requests the player API with credentials', async () => {
    const fetchImpl = createFetch()
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)
    await adapter.getSubtitleTracks()
    expect(fetchImpl).toHaveBeenCalledWith(
      expect.stringContaining('/x/player/v2'),
      expect.objectContaining({ credentials: 'include' }),
    )
  })

  it('falls back to YouTube captions when Bilibili has none but the description has a source link', async () => {
    const context = {
      ...bridgePayload,
      description: '原视频 https://www.youtube.com/watch?v=dQw4w9WgXcQ',
    }
    const sourceResponse = {
      ...youtubePlayerResponse,
      videoDetails: {
        ...youtubePlayerResponse.videoDetails,
        videoId: 'dQw4w9WgXcQ',
      },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: youtubePlayerResponse.captions.playerCaptionsTracklistRenderer.captionTracks.map(
            (track) => ({
              ...track,
              baseUrl: track.baseUrl.replace('v=test123', 'v=dQw4w9WgXcQ'),
            }),
          ),
        },
      },
    }
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = typeof input === 'string' ? input : input.toString()
      if (url.includes('/x/player/v2') || url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('youtubei/v1/player')) {
        return new Response(JSON.stringify(sourceResponse), { status: 200 })
      }
      if (url.includes('timedtext')) {
        return new Response(JSON.stringify({
          events: [
            { tStartMs: 0, dDurationMs: 1000, segs: [{ utf8: 'Hello from YouTube.' }] },
          ],
        }), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter(context, fetchImpl)
    const tracks = await adapter.getSubtitleTracks()

    expect(tracks.some((track) => track.label.includes('YouTube'))).toBe(true)
    const english = tracks.find((track) => track.language === 'en')
    expect(english).toBeDefined()
    await expect(adapter.getCues(english!)).resolves.toEqual([
      {
        id: 'yt-0',
        startMs: 0,
        endMs: 1000,
        text: 'Hello from YouTube.',
      },
    ])
  })

  it('loads the exact manually selected YouTube source without auto-matching another candidate', async () => {
    const manualVideoId = 'dQw4w9WgXcQ'
    const sourceResponse = {
      ...youtubePlayerResponse,
      videoDetails: {
        ...youtubePlayerResponse.videoDetails,
        videoId: manualVideoId,
        title: 'Manually selected source',
        lengthSeconds: '4996',
      },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: youtubePlayerResponse.captions.playerCaptionsTracklistRenderer.captionTracks.map(
            (track) => ({
              ...track,
              baseUrl: track.baseUrl.replace('v=test123', `v=${manualVideoId}`),
            }),
          ),
        },
      },
    }
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('/x/player/v2') || url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('youtubei/v1/player')) {
        return new Response(JSON.stringify(sourceResponse), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter({
      ...bridgePayload,
      description: '无关链接 https://youtu.be/abcdefghijk',
    }, fetchImpl)

    const tracks = await adapter.useManualYouTubeSource(manualVideoId)

    expect(tracks).not.toHaveLength(0)
    expect(tracks.every((track) => track.id.includes(manualVideoId))).toBe(true)
    expect(tracks[0]).toMatchObject({
      sourceDurationMs: 4_996_000,
      label: expect.stringContaining('Manually selected source'),
    })
  })

  it('rejects a manual source response that belongs to another YouTube video', async () => {
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = input.toString()
      if (url.includes('youtubei/v1/player')) {
        return new Response(JSON.stringify({
          ...youtubePlayerResponse,
          videoDetails: {
            ...youtubePlayerResponse.videoDetails,
            videoId: 'abcdefghijk',
          },
        }), { status: 200 })
      }
      if (url.includes('/watch')) return new Response('', { status: 404 })
      return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
    })
    const adapter = new BilibiliAdapter(bridgePayload, fetchImpl)

    await expect(adapter.useManualYouTubeSource('dQw4w9WgXcQ')).rejects.toThrow(
      /无法读取这个 YouTube 原视频/,
    )
  })

  it('ignores a shorter unrelated YouTube link and keeps the duration-matched source', async () => {
    const foodResponse = {
      ...youtubePlayerResponse,
      videoDetails: {
        ...youtubePlayerResponse.videoDetails,
        videoId: 'bbbbbbbbbbb',
        title: '厦门姜母鸭探店',
        lengthSeconds: '600',
      },
    }
    const interviewResponse = {
      ...youtubePlayerResponse,
      videoDetails: {
        ...youtubePlayerResponse.videoDetails,
        videoId: 'ccccccccccc',
        title: 'The Economist interviews Elon Musk',
        lengthSeconds: '3600',
      },
    }
    const context = {
      ...bridgePayload,
      title: '《经济学人》杂志主编对埃隆·马斯克的访谈',
      durationMs: 3_600_000,
      description: '更多 https://youtu.be/bbbbbbbbbbb 原视频 https://youtu.be/ccccccccccc',
    }
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = typeof input === 'string' ? input : input.toString()
      if (url.includes('/x/player/v2') || url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('youtubei/v1/player')) {
        const videoId = JSON.parse(String(init?.body ?? '{}')).videoId as string
        const body = videoId === 'bbbbbbbbbbb' ? foodResponse : interviewResponse
        return new Response(JSON.stringify(body), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter(context, fetchImpl)
    const tracks = await adapter.getSubtitleTracks()

    expect(tracks.every((track) => track.label.includes('Elon Musk') || track.label.includes('YouTube'))).toBe(true)
    expect(tracks.some((track) => track.label.includes('姜母鸭'))).toBe(false)
    expect(tracks.every((track) => track.id.includes('ccccccccccc'))).toBe(true)
  })

  it('does not fall back to a mismatched YouTube video', async () => {
    const foodResponse = {
      ...youtubePlayerResponse,
      videoDetails: {
        ...youtubePlayerResponse.videoDetails,
        videoId: 'bbbbbbbbbbb',
        title: '厦门姜母鸭探店',
        lengthSeconds: '600',
      },
    }
    const context = {
      ...bridgePayload,
      title: '《经济学人》杂志主编对埃隆·马斯克的访谈',
      durationMs: 3_600_000,
      description: 'https://youtu.be/bbbbbbbbbbb',
    }
    const fetchImpl = vi.fn().mockImplementation(async (input: RequestInfo | URL) => {
      const url = typeof input === 'string' ? input : input.toString()
      if (url.includes('/x/player/v2') || url.includes('/x/web-interface/view')) {
        return new Response(JSON.stringify({ code: 0, data: {} }), { status: 200 })
      }
      if (url.includes('youtubei/v1/player')) {
        return new Response(JSON.stringify(foodResponse), { status: 200 })
      }
      return new Response('{}', { status: 404 })
    })
    const adapter = new BilibiliAdapter(context, fetchImpl)

    await expect(adapter.getSubtitleTracks()).rejects.toMatchObject({ code: 'NO_SUBTITLE' })
  })
})
