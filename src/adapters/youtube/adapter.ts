import { AppError } from '../../errors/app-error'
import { CaptionTrackSchema } from './schemas'
import type { SubtitleAdapter, SubtitleTrack, SubtitleCue, VideoMetadata } from '../../core/contracts'
import type { BridgePayload } from '../shared/page-bridge'
import { measureSubtitleQuality } from '../../processors/subtitle-quality'

const ALLOWED_CAPTION_HOSTS = new Set([
  'www.youtube.com',
  'youtube.com',
  'www.google.com',
])

export class YouTubeAdapter implements SubtitleAdapter {
  private readonly payload: BridgePayload
  private readonly fetchImpl: typeof fetch
  private readonly captionLoader?: (trackId: string) => Promise<Response>

  constructor(
    payload: BridgePayload,
    fetchImpl: typeof fetch = globalThis.fetch.bind(globalThis),
    captionLoader?: (trackId: string) => Promise<Response>,
  ) {
    this.payload = payload
    this.fetchImpl = fetchImpl
    this.captionLoader = captionLoader
  }

  supports(url: URL): boolean {
    return url.hostname === 'www.youtube.com' || url.hostname === 'youtube.com'
  }

  async getVideoMetadata(): Promise<VideoMetadata> {
    const { videoId, metadata } = this.payload
    return {
      platform: 'youtube',
      videoId,
      title: metadata.title,
      author: metadata.author,
      canonicalUrl: `https://www.youtube.com/watch?v=${videoId}`,
      durationMs: metadata.durationMs,
    }
  }

  async getSubtitleTracks(): Promise<SubtitleTrack[]> {
    const { tracks } = this.payload
    if (tracks.length === 0) {
      throw new AppError('NO_SUBTITLE', '当前视频无可访问的字幕')
    }
    return tracks.map((t) => ({
      id: t.vssId,
      language: t.languageCode,
      label: t.label,
      isAutoGenerated: t.isAutoGenerated,
      sourceGroup: `youtube:${this.payload.videoId}`,
    }))
  }

  async getCues(track: SubtitleTrack): Promise<SubtitleCue[]> {
    const trackInfo = this.payload.tracks.find((t) => t.vssId === track.id)
    if (!trackInfo) {
      throw new AppError('SUBTITLE_EXTRACTION_FAILED', '未找到指定的字幕轨道')
    }

    // Validate HTTPS
    const urls = this.captionLoader
      ? [trackInfo.baseUrl]
      : [...new Set([trackInfo.baseUrl, ...(trackInfo.alternateBaseUrls ?? [])])]
    const results = await Promise.all(urls.map(async (url) => {
      try {
        return { cues: await this.fetchCues(url, trackInfo.vssId), error: null }
      } catch (error) {
        return { cues: [] as SubtitleCue[], error }
      }
    }))
    let bestCues: SubtitleCue[] = []
    for (const result of results) {
      if (isBetterCaptionSet(result.cues, bestCues, this.payload.metadata.durationMs)) {
        bestCues = result.cues
      }
    }
    if (bestCues.length > 0) return bestCues
    const firstError = results.find((result) => result.error !== null)?.error
    if (firstError instanceof AppError) throw firstError
    throw new AppError('SUBTITLE_EXTRACTION_FAILED', 'YouTube 字幕轨道没有可提取的文字内容')
  }

  private async fetchCues(baseUrl: string, trackId: string): Promise<SubtitleCue[]> {
    const parsedUrl = new URL(baseUrl)
    if (
      parsedUrl.protocol !== 'https:' ||
      (!ALLOWED_CAPTION_HOSTS.has(parsedUrl.hostname) &&
        !parsedUrl.hostname.endsWith('.googlevideo.com'))
    ) {
      throw new AppError('SUBTITLE_EXTRACTION_FAILED', '字幕地址不在允许的 YouTube 域名内')
    }

    // Ensure fmt=json3 is set
    const captionVideoId = parsedUrl.searchParams.get('v')
    if (captionVideoId !== null && captionVideoId !== this.payload.videoId) {
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        'YouTube 字幕地址与当前视频不一致，已停止提取以避免生成其他视频的内容',
      )
    }
    parsedUrl.searchParams.set('fmt', 'json3')

    let response: Response
    try {
      response = this.captionLoader
        ? await this.captionLoader(trackId)
        : await this.fetchImpl(parsedUrl.toString(), {
          credentials: 'include',
          headers: { Accept: 'application/json' },
          signal: AbortSignal.timeout(20_000),
        })
    } catch (e) {
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        `字幕数据获取失败: ${e instanceof Error ? e.message : '网络错误'}`,
      )
    }

    if (!response.ok) {
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        `字幕请求失败 (HTTP ${response.status})`,
      )
    }

    // Read as text first, then try JSON
    const rawText = await response.text().catch(() => '')
    if (rawText.trim().length === 0) {
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        'YouTube 返回了空字幕数据，请刷新视频页面后重试',
      )
    }
    if (rawText.trimStart().startsWith('<')) {
      return requireCaptionCues(parseXmlCaptions(rawText))
    }

    let body: unknown
    try {
      body = JSON.parse(rawText)
    } catch {
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        `字幕数据格式异常，响应既不是 XML 也不是 JSON。响应预览: ${rawText.slice(0, 200)}`,
      )
    }

    const parsed = CaptionTrackSchema.safeParse(body)
    if (!parsed.success) {
      const keys = typeof body === 'object' && body !== null
        ? Object.keys(body as Record<string, unknown>).join(', ')
        : typeof body
      throw new AppError(
        'SUBTITLE_EXTRACTION_FAILED',
        `字幕数据结构不符合预期。返回字段: ${keys || '(空)'}`,
      )
    }

    const cues = parsed.data.events
      .map((event, index) => ({
        id: `yt-${index}`,
        startMs: event.tStartMs,
        endMs: event.tStartMs + event.dDurationMs,
        text: event.segs.map((seg) => seg.utf8).join(''),
      }))
      .filter((cue) => cue.text.trim().length > 0)
    return requireCaptionCues(cues)
  }
}

function isBetterCaptionSet(
  candidate: SubtitleCue[],
  current: SubtitleCue[],
  durationMs?: number,
): boolean {
  if (current.length === 0) return candidate.length > 0
  const candidateQuality = measureSubtitleQuality(candidate, durationMs)
  const currentQuality = measureSubtitleQuality(current, durationMs)
  if (candidateQuality.endMs !== currentQuality.endMs) {
    return candidateQuality.endMs > currentQuality.endMs
  }
  if (candidateQuality.textChars !== currentQuality.textChars) {
    return candidateQuality.textChars > currentQuality.textChars
  }
  return candidateQuality.cueCount > currentQuality.cueCount
}

function requireCaptionCues(cues: SubtitleCue[]): SubtitleCue[] {
  if (cues.length === 0) {
    throw new AppError(
      'SUBTITLE_EXTRACTION_FAILED',
      'YouTube 字幕轨道没有可提取的文字内容，请切换字幕或刷新页面后重试',
    )
  }
  return cues
}

function parseXmlCaptions(rawText: string): SubtitleCue[] {
  const documentNode = new DOMParser().parseFromString(rawText, 'text/xml')
  if (documentNode.querySelector('parsererror')) {
    throw new AppError('SUBTITLE_EXTRACTION_FAILED', 'YouTube XML 字幕解析失败')
  }
  return [...documentNode.querySelectorAll('text')]
    .map((node, index) => {
      const startSeconds = Number(node.getAttribute('start') ?? '0')
      const durationSeconds = Number(node.getAttribute('dur') ?? '0')
      return {
        id: `yt-${index}`,
        startMs: Math.round(startSeconds * 1000),
        endMs: Math.round((startSeconds + durationSeconds) * 1000),
        text: node.textContent ?? '',
      }
    })
    .filter((cue) => cue.text.trim().length > 0)
}
